-- Mlimani AI Studio PostgreSQL foundation.
-- Intentionally isolated from Mlimani Fleet's public schema.
-- Review and apply only after the backend adapter and backup/migration procedure are ready.
CREATE SCHEMA IF NOT EXISTS ainew;

CREATE TABLE IF NOT EXISTS ainew.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT UNIQUE,
  phone TEXT UNIQUE,
  name TEXT,
  pass TEXT NOT NULL,
  plan TEXT NOT NULL DEFAULT 'free',
  expires BIGINT NOT NULL DEFAULT 0,
  credit_used DOUBLE PRECISION NOT NULL DEFAULT 0,
  created BIGINT
);

CREATE TABLE IF NOT EXISTS ainew.daily (
  k TEXT NOT NULL,
  d TEXT NOT NULL,
  n INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (k, d)
);

CREATE TABLE IF NOT EXISTS ainew.bots (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES ainew.users(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  prompt TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS bots_user_id_idx ON ainew.bots(user_id);

CREATE TABLE IF NOT EXISTS ainew.api_keys (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES ainew.users(id) ON DELETE CASCADE,
  name TEXT,
  prefix TEXT,
  hash TEXT UNIQUE,
  created BIGINT,
  last_used BIGINT,
  revoked INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS api_keys_user_id_idx ON ainew.api_keys(user_id);

CREATE TABLE IF NOT EXISTS ainew.connections (
  user_id BIGINT NOT NULL REFERENCES ainew.users(id) ON DELETE CASCADE,
  provider TEXT NOT NULL,
  secret TEXT,
  meta TEXT,
  created BIGINT,
  PRIMARY KEY (user_id, provider)
);

CREATE TABLE IF NOT EXISTS ainew.plugin_prefs (
  user_id BIGINT NOT NULL REFERENCES ainew.users(id) ON DELETE CASCADE,
  plugin_id TEXT NOT NULL,
  enabled INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (user_id, plugin_id)
);

CREATE TABLE IF NOT EXISTS ainew.payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES ainew.users(id) ON DELETE CASCADE,
  plan TEXT NOT NULL,
  phone TEXT,
  ref TEXT NOT NULL UNIQUE,
  status TEXT NOT NULL DEFAULT 'pending',
  created BIGINT
);
CREATE INDEX IF NOT EXISTS payments_user_id_idx ON ainew.payments(user_id);

CREATE TABLE IF NOT EXISTS ainew.partner_applications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company TEXT NOT NULL,
  contact TEXT NOT NULL,
  email TEXT NOT NULL,
  website TEXT,
  api_url TEXT,
  description TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending',
  created BIGINT
);

CREATE TABLE IF NOT EXISTS ainew.composio_usage (
  user_id BIGINT NOT NULL REFERENCES ainew.users(id) ON DELETE CASCADE,
  month TEXT NOT NULL,
  calls INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (user_id, month)
);

CREATE TABLE IF NOT EXISTS ainew.studio_chat_sessions (
  session_id TEXT PRIMARY KEY,
  owner_key TEXT NOT NULL,
  duration_tier TEXT NOT NULL,
  started_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS studio_chat_sessions_expiry_idx ON ainew.studio_chat_sessions(expires_at);
